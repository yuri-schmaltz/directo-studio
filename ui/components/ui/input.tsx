  HTMLTextAreaElement,
  React.TextareaHTMLAttributes<HTMLTextAreaElement>
>(({ className, ...props }, ref) => (
  <textarea
    ref={ref}
    className={cn(
      "input h-auto min-h-[80px] py-2 font-mono text-sm leading-relaxed",
      className,
    )}
    {...props}
  />
));
Textarea.displayName = "Textarea";

